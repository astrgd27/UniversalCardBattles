// Compiles every default module that has a Workshop blueprint (packages/modules/<id>/blueprint.json) into its module
// files (manifest, rules, cards, decks, ai), so the shipped games stay editable in the Workshop. Usage: npm run -s modules
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { compileModule, validateIssues, issueText } from '#engine';
import { compileBlueprint } from '../../maker/src/compile.ts';
import { MOD_DIR } from './index.ts';

let bad = 0;
for (const id of readdirSync(MOD_DIR)) {
  const f = join(MOD_DIR, id, 'blueprint.json');
  if (!existsSync(f)) continue;
  const def = compileBlueprint(JSON.parse(readFileSync(f, 'utf8'))) as any;
  const issues = validateIssues(def);
  for (const i of issues) console.log(`${id}: ${issueText(i)}`);
  bad += issues.length;
  compileModule(def);
  const w = (name: string, v: unknown) => writeFileSync(join(MOD_DIR, id, name), JSON.stringify(v) + '\n');
  w('manifest.json', def.manifest); w('rules.json', def.rules); w('cards.json', def.cards); w('decks.json', def.decks);
  mkdirSync(join(MOD_DIR, id, 'ai'), { recursive: true });
  w('ai/ai.json', def.ai);
  console.log(`${id}: ${def.cards.length} cards, ${Object.keys(def.decks).length} decks`);
}
// usage counts: how often each ability-builder option appears in the default games, so the Workshop lists the most used first
const U: Record<string, Record<string, number>> = { effect: {}, when: {}, cond: {}, target: {}, amount: {} };
const inc = (k: string, v?: string) => { if (v) U[k][v] = (U[k][v] ?? 0) + 1; };
const effs = (list: any[] = []): void => { for (const e of list) { inc('effect', e.k); inc('target', e.target); inc('amount', e.amount?.of); effs(e.heads); effs(e.tails); effs(e.then); for (const r of e.ranges ?? []) effs(r.do); } };
const cond = (c: any): void => { if (!c) return; inc('cond', c.k); for (const q of c.of ?? []) cond(q); };
const abil = (a: any) => { inc('when', a.when); cond(a.if); effs(a.do); };
for (const id of readdirSync(MOD_DIR).sort()) {
  const f = join(MOD_DIR, id, 'blueprint.json');
  if (!existsSync(f)) continue;
  const bp = JSON.parse(readFileSync(f, 'utf8'));
  for (const c of bp.cards) for (const a of c.abilities ?? []) abil(a);
  for (const k of bp.keywords ?? []) for (const a of k.abilities ?? []) abil(a);
  for (const m of bp.meters ?? []) for (const st of m.steps ?? []) effs(st.do);
}
const sorted = Object.fromEntries(Object.entries(U).map(([k, v]) => [k, Object.fromEntries(Object.entries(v).sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])))]));
writeFileSync(join(MOD_DIR, '..', 'maker', 'src', 'usage.ts'), `// Generated by \`npm run -s modules\` from the default games' blueprints: how often each ability-builder option is used.
// The Workshop lists the most used options first (see apps/web/src/ui/maker.ts \`ranked\`). Do not edit by hand.
export const USAGE: Record<'effect' | 'when' | 'cond' | 'target' | 'amount', Record<string, number>> = ${JSON.stringify(sorted, null, 1)};
`);
process.exitCode = bad ? 1 : 0;
